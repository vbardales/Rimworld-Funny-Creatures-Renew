<#
.SYNOPSIS
  Builds FRENCH_REVIEW.md from the shipped DefInjected XML, for TRANSLATIONS.md's
  "Systematic French review by Virginie" (2026-09-30).
.DESCRIPTION
  This mod has no Keyed folder and no Languages/English folder: the original mod
  (PredatorKing's, ported from 1.3) is itself in English, so the English text IS the
  native fallback read straight from Mod/Defs, and there is no separate source-language
  original either — Original and English are the same text throughout, stated once here
  rather than on every row, per TRANSLATIONS.md.

  Two DefInjected files ship: ThingDef/FunnyCreatures.xml (label, description, race
  meatLabel, tool labels) and PawnKindDef/FunnyCreatures.xml (label, life-stage label
  and labelPlural). Reads every French key, resolves the matching Def field by dotted
  path against the shipped Def XML in Mod/Defs — tool and life-stage list entries have
  no numeric DefInjected index in this mod, they are addressed by an underscore slug of
  their own English label (e.g. "left_hoof" -> the tool whose <label> is "left hoof"),
  resolved by scanning the list rather than assumed by position, so a reordering in Defs
  cannot silently mismatch a row.
#>
param(
    [string]$Root = (Split-Path $PSScriptRoot -Parent),
    [string]$OutFile = (Join-Path (Split-Path $PSScriptRoot -Parent) 'FRENCH_REVIEW.md')
)

function Get-Entries($path) {
    $entries = [ordered]@{}
    if (-not (Test-Path $path)) { return $entries }
    $xml = [xml](Get-Content $path -Raw -Encoding UTF8)
    foreach ($node in $xml.LanguageData.ChildNodes) {
        if ($node.NodeType -ne 'Element') { continue }
        $entries[$node.Name] = $node.InnerText
    }
    return $entries
}

function Find-DefNode($defsRoot, [string]$defType, [string]$defName) {
    # A ThingDef and a PawnKindDef in this mod share the same defName (Meffalo,
    # Boomsloth): match on element type too, or the wrong sibling comes back.
    $cacheKey = "$defType/$defName"
    if ($script:defCache.ContainsKey($cacheKey)) { return $script:defCache[$cacheKey] }
    $found = $null
    foreach ($f in $script:defFiles) {
        $x = [xml](Get-Content $f -Raw -Encoding UTF8)
        $node = $x.SelectSingleNode("//$defType[defName='$defName']")
        if ($node) { $found = $node; break }
    }
    $script:defCache[$cacheKey] = $found
    return $found
}

function Find-BySlug($listNode, [string]$slug, [string]$field) {
    # $listNode is the <tools> or <lifeStages> element; each <li> child may or may not
    # carry <label>. Match the child whose label, lowercased and space->underscore,
    # equals $slug.
    if (-not $listNode) { return $null }
    foreach ($li in $listNode.ChildNodes) {
        if ($li.NodeType -ne 'Element') { continue }
        $lbl = $li.label
        if (-not $lbl) { continue }
        $candidate = ($lbl.ToLowerInvariant() -replace ' ', '_')
        if ($candidate -eq $slug) {
            if ($field -eq 'label') { return $lbl }
            $child = $li.$field
            if ($child -is [System.Xml.XmlElement]) { return $child.InnerText }
            if ($child) { return [string]$child }
            return $null
        }
    }
    return $null
}

function Resolve-DefField($defsRoot, [string]$defType, [string]$key) {
    # "DefName.field", "DefName.race.field", "DefName.tools.<slug>.label",
    # "DefName.lifeStages.<slug>.label" / ".labelPlural"
    $parts = $key -split '\.'
    $defName = $parts[0]
    $node = Find-DefNode $defsRoot $defType $defName
    if (-not $node) { return $null }

    if ($parts.Count -eq 2 -and $parts[1] -in @('label', 'description')) {
        $v = $node.($parts[1])
        if ($v) { return [string]$v }
        return $null
    }
    if ($parts.Count -eq 3 -and $parts[1] -eq 'race') {
        $v = $node.race.($parts[2])
        if ($v) { return [string]$v }
        return $null
    }
    if ($parts.Count -eq 4 -and $parts[1] -eq 'tools') {
        return Find-BySlug $node.tools $parts[2] $parts[3]
    }
    if ($parts.Count -eq 4 -and $parts[1] -eq 'lifeStages') {
        return Find-BySlug $node.lifeStages $parts[2] $parts[3]
    }
    return $null
}

$frenchRoot = Join-Path $Root 'Mod/Languages/French/DefInjected'
$defsRoot = Join-Path $Root 'Mod/Defs'
$script:defFiles = Get-ChildItem $defsRoot -Recurse -Filter *.xml | ForEach-Object { $_.FullName }
$script:defCache = @{}

$frenchFiles = Get-ChildItem $frenchRoot -Recurse -Filter *.xml | Sort-Object FullName
$out = New-Object System.Text.StringBuilder
$modName = ([xml](Get-Content (Join-Path $Root 'Mod/About/About.xml') -Raw -Encoding UTF8)).ModMetaData.name
$rev = (git -C $Root log -1 --format=%h -- Mod/Languages Mod/Defs).Trim()
[void]$out.AppendLine("# French review - $modName")
[void]$out.AppendLine()
[void]$out.AppendLine("Generated by ``_tools/Generate-FrenchReview.ps1`` for TRANSLATIONS.md's systematic French review.")
[void]$out.AppendLine()
[void]$out.AppendLine("**No Keyed folder, no Languages/English folder, and Original = English throughout.** The")
[void]$out.AppendLine("mod ports PredatorKing's original (2640466629), itself in English with no separate")
[void]$out.AppendLine("source-language text anywhere in this repository, to RimWorld 1.6. English is read")
[void]$out.AppendLine("straight from the shipped Def field, the game's own native fallback; Original is the")
[void]$out.AppendLine("same field, said once here rather than on every row.")
[void]$out.AppendLine()
[void]$out.AppendLine("Generated $(Get-Date -Format 'yyyy-MM-dd'), revision $rev (last commit touching Mod/Languages or Mod/Defs), no gender-agreement")
[void]$out.AppendLine("switches in this mod (no French text agrees with a pawn's gender).")
[void]$out.AppendLine()

foreach ($ff in $frenchFiles) {
    $rel = ($ff.FullName.Substring($frenchRoot.Length + 1) -replace '\\', '/')
    $defType = ($rel -split '[\\/]')[0]
    $rel = "DefInjected/$rel"
    $frEntries = Get-Entries $ff.FullName
    if ($frEntries.Count -eq 0) { continue }

    [void]$out.AppendLine("## $rel")
    [void]$out.AppendLine()
    [void]$out.AppendLine("| Key or path | Original | English | French |")
    [void]$out.AppendLine("|---|---|---|---|")
    foreach ($key in $frEntries.Keys) {
        $fr = $frEntries[$key]
        $orig = Resolve-DefField $defsRoot $defType $key
        $en = $orig
        if ($null -eq $orig) { $orig = '*(not found - check by hand)*'; $en = $orig }
        $flag = if ($fr -match '\?\?\?|TODO|\{PAWN_gender' -and $fr -notmatch '\{PAWN_gender \? ') { ' | ?' } else { '' }
        $origCell = ($orig -replace '\|', '\|') -replace "`n", ' '
        $enCell = ($en -replace '\|', '\|') -replace "`n", ' '
        $frCell = ($fr -replace '\|', '\|') -replace "`n", ' '
        $keyCell = $key -replace '\|', '\|'
        [void]$out.AppendLine("| $keyCell | $origCell | $enCell | $frCell$flag |")
    }
    [void]$out.AppendLine()
}

[System.IO.File]::WriteAllText($OutFile, $out.ToString(), (New-Object System.Text.UTF8Encoding($false)))
Write-Output "wrote $OutFile"
